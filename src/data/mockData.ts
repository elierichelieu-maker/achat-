export function generateInitialSales(): Sale[] {
  const sales: Sale[] = [];
  const baseDate = new Date('2026-10-22T12:00:00Z');

  // CHR Clients: Bars, Restaurants, Clubs, Events, Cavistes
  const clients = [
    { name: 'Julien Tavernier', company: 'Brasserie du Port & Terrasse' },
    { name: 'Élodie Marchand', company: 'Le Rooftop Lounge Bar' },
    { name: 'Alexandre Meyer', company: 'Hôtel & Spa Le Grand Cerf' },
    { name: 'Nathalie Vasseur', company: 'Bar & Club L\'Arpège' },
    { name: 'François Delorme', company: 'Bistrot Parisien Chez Marcel' },
    { name: 'Camille Roche', company: 'Festival Musiques & Bulles SAS' },
    { name: 'Benoît Giraud', company: 'Caviste Les Vignes & Nectars' },
    { name: 'Sandrine Morel', company: 'Plage Privée Le Sunset Club' },
    { name: 'Maxime Bertrand', company: 'Guinguette des Bords de Seine' },
    { name: 'Karim Mansouri', company: 'Traiteur & Réceptions Élite' },
  ];

  const paymentMethods: Sale['paymentMethod'][] = ['virement', 'traite', 'carte', 'virement', 'especes'];
  let invoiceCounter = 3410;

  for (let i = 28; i >= 0; i--) {
    const dayDate = new Date(baseDate);
    dayDate.setDate(baseDate.getDate() - i);
    const dayTransactions = (i % 7 === 0 || i % 7 === 6) ? 2 : (1 + (i * 2) % 3);

    for (let t = 0; t < dayTransactions; t++) {
      invoiceCounter++;
      const seller = INITIAL_SELLERS[(i + t) % INITIAL_SELLERS.length];
      const client = clients[(i * 3 + t) % clients.length];

      // Pick 1 to 3 beverage products
      const p1 = INITIAL_PRODUCTS[(i * 2 + t) % INITIAL_PRODUCTS.length];
      const qty1 = p1.isConsigne ? (2 + (i % 4)) : (3 + (i * 2 % 6));

      const items = [
        {
          productId: p1.id,
          productName: p1.name,
          quantity: qty1,
          unitCost: p1.costPrice,
          unitPrice: p1.salePrice,
          totalPrice: p1.salePrice * qty1,
          totalCost: p1.costPrice * qty1,
          profit: (p1.salePrice - p1.costPrice) * qty1,
          marginPercent: Math.round(((p1.salePrice - p1.costPrice) / p1.salePrice) * 100),
        },
      ];

      // Add a complementary product (e.g. sodas + beers or spirits + tonics)
      if ((i + t) % 2 === 0) {
        const p2 = INITIAL_PRODUCTS[(i + t + 4) % INITIAL_PRODUCTS.length];
        const qty2 = 2 + (i % 3);
        items.push({
          productId: p2.id,
          productName: p2.name,
          quantity: qty2,
          unitCost: p2.costPrice,
          unitPrice: p2.salePrice,
          totalPrice: p2.salePrice * qty2,
          totalCost: p2.costPrice * qty2,
          profit: (p2.salePrice - p2.costPrice) * qty2,
          marginPercent: Math.round(((p2.salePrice - p2.costPrice) / p2.salePrice) * 100),
        });
      }

      const totalHT = items.reduce((acc, it) => acc + it.totalPrice, 0);
      const totalCost = items.reduce((acc, it) => acc + it.totalCost, 0);
      const netProfit = totalHT - totalCost;
      const marginPercent = Math.round((netProfit / totalHT) * 100);
      const taxRate = 0.20;
      const totalTTC = Math.round(totalHT * (1 + taxRate) * 100) / 100;

      const saleTime = new Date(dayDate);
      saleTime.setHours(8 + ((t * 3 + i) % 11), (t * 19 + i * 13) % 60, 0);

      sales.push({
        id: `sale-${invoiceCounter}`,
        invoiceNumber: `LIV-2026-${invoiceCounter}`,
        date: saleTime.toISOString(),
        sellerId: seller.id,
        sellerName: seller.name,
        customerName: client.name,
        customerCompany: client.company,
        items,
        totalHT,
        taxRate,
        totalTTC,
        totalCost,
        netProfit,
        marginPercent,
        status: 'completed',
        paymentMethod: paymentMethods[(i + t) % paymentMethods.length],
      });
    }
  }

  return sales;
}

